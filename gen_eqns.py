def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--table-homotopy", action="store_true",
                    help="blend old and new property tables through hom_tab; "
                         "requires both sets loaded, named cp_old/cp_new etc.")
    ap.add_argument("--out", type=Path,
                    default=Path(__file__).resolve().parent.parent / "eqns_named.txt")
    args = ap.parse_args()
    global TABLE_HOM
    TABLE_HOM = args.table_homotopy

    header(); inputs(); areas_flows(); pressures(); transport(); refprop_states()
    pressure_drop_segments(); machines()
    recuperator("HTR", "HTR_HP", "HTR_LP", "A_HTR",
                S[12], S[4], S[6], S[7], "m_dot_hot", "m_dot_hot")
    recuperator("LTR", "LTR_HP", "LTR_LP", "A_LTR",
                S[2], S[11], S[7], S[8], "m_dot_cold", "m_dot_hot")
    closure(); plot_arrays(); units()

