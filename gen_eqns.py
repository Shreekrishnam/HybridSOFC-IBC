#!/usr/bin/env python
"""
gen_eqns.py
===========
Emit the renamed sCO2 recompression-cycle model (checkpoint C2.3).

The legacy model indexes every state in one flat array, 1..12 for the cycle and
12 + k*d_p + n for the four recuperator sides. Three of the bugs fixed in Phase 0
were index-arithmetic errors in exactly that scheme. This generator emits the same
physics with named scalars and per-side arrays, so no equation contains
12 + k*d_p + n arithmetic anywhere.

Physics is UNCHANGED. Every equation below is a renaming of one in eqns.txt as of
the stage-5 model. Two structural artefacts are dropped deliberately:

  * P[333], a phantom created by `P[p] = P[p+1]` running one past the LTR
    low-pressure chain. The named chain cannot express it.
  * The paired REFPROP TP calls (one for h, one for s, same inputs) are merged
    into one call per point - checkpoint C6.1, a straight 2x on the dominant cost.

Naming comes from gen_state_map.py; change CYCLE_STATES there and re-run both.

Usage:
    python gen_eqns.py --d-p 80 --out ../eqns_named.txt
"""

